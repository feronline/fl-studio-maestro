"""Exports: a multi-track Standard MIDI File of the arrangement, and FL piano roll scripts per pattern."""

from __future__ import annotations

import struct
from pathlib import Path
from typing import Any

from . import paths
from .project import Project

PPQ = 480


def _vlq(value: int) -> bytes:
    out = [value & 0x7F]
    value >>= 7
    while value:
        out.append((value & 0x7F) | 0x80)
        value >>= 7
    return bytes(reversed(out))


def _meta(kind: int, data: bytes) -> bytes:
    return bytes([0xFF, kind]) + _vlq(len(data)) + data


def _track(events: list[tuple[int, int, bytes]]) -> bytes:
    """events: (tick, order, raw bytes). order breaks ties (note-offs before note-ons)."""
    body, last = b"", 0
    for tick, _, raw in sorted(events, key=lambda e: (e[0], e[1])):
        body += _vlq(tick - last) + raw
        last = tick
    body += b"\x00" + _meta(0x2F, b"")
    return b"MTrk" + struct.pack(">I", len(body)) + body


def export_midi(proj: Project, out: Path | None = None) -> dict[str, Any]:
    d, bpb = proj.data, proj.beats_per_bar
    if not d["arrangement"]:
        raise ValueError("the arrangement is empty: call arrange first")
    out = out or proj.dir / f"{d['slug']}.mid"
    out.parent.mkdir(parents=True, exist_ok=True)

    tempo = round(60_000_000 / d["bpm"])
    den_pow = {1: 0, 2: 1, 4: 2, 8: 3, 16: 4, 32: 5}[d["ts_den"]]
    conductor = [
        (0, 0, _meta(0x03, d["name"].encode("utf-8"))),
        (0, 1, _meta(0x51, tempo.to_bytes(3, "big"))),
        (0, 2, _meta(0x58, bytes([d["ts_num"], den_pow, 24, 8]))),
    ]
    for s in d["sections"]:
        tick = round((s["start_bar"] - 1) * bpb * PPQ)
        conductor.append((tick, 3, _meta(0x06, s["name"].encode("utf-8"))))

    tracks = [_track(conductor)]
    next_ch = 0
    summary = []
    # One track per agent in Channel Rack order, so FL's MIDI import lines channels up with agents.
    for agent in sorted(d["agents"].values(), key=lambda a: a["channel"]):
        if agent["role"] in ("drums", "percussion"):
            ch = 9
        else:
            if next_ch == 9:
                next_ch += 1
            ch = next_ch % 16
            next_ch += 1
        events = [(0, 0, _meta(0x03, agent["name"].encode("utf-8")))]
        count = 0
        for pl in d["arrangement"]:
            pat = d["patterns"][pl["pattern"]]
            if pat["agent"] != agent["id"]:
                continue
            for rep in range(pl["repeat"]):
                base = (pl["start_bar"] - 1) * bpb + rep * pat["length_beats"]
                for n in pat["notes"]:
                    on = round((base + n["start"]) * PPQ)
                    off = max(on + 1, round((base + n["start"] + n["length"]) * PPQ))
                    events.append((on, 2, bytes([0x90 | ch, n["pitch"], n["velocity"]])))
                    events.append((off, 1, bytes([0x80 | ch, n["pitch"], 0])))
                    count += 1
        tracks.append(_track(events))
        summary.append({"agent": agent["id"], "fl_channel": agent["channel"], "midi_channel": ch + 1, "notes": count})

    header = b"MThd" + struct.pack(">IHHH", 6, 1, len(tracks), PPQ)
    out.write_bytes(header + b"".join(tracks))
    return {"file": str(out), "tracks": summary, "bars": proj.song_bars(), "ppq": PPQ}


_SCRIPT = '''"""Maestro OS - {project}: {pattern_name}
Agent: {agent_name} ({agent_id}) | FL channel {channel} | FL pattern {fl_pattern} | {length:g} beats
Generated by fl-studio-maestro. Open the pattern's piano roll, then run this script.
"""
import flpianoroll as flp

# (MIDI pitch, start beat, length in beats, velocity 0-1)
NOTES = {notes}


def createDialog():
    form = flp.ScriptDialog("Maestro: {pattern_name}",
                            "Writes {count} notes for {agent_name} (pattern {fl_pattern}). "
                            "Open the right channel's piano roll first.")
    form.AddInputCheckbox("Replace existing notes", True)
    return form


def apply(form):
    if form.GetInputValue("Replace existing notes"):
        flp.score.clearNotes(True)
    ppq = flp.score.PPQ
    for pitch, start, length, velocity in NOTES:
        note = flp.Note()
        note.number = pitch
        note.time = int(round(start * ppq))
        note.length = max(1, int(round(length * ppq)))
        note.velocity = velocity
        flp.score.addNote(note)
'''


def script_name(proj: Project, pat: dict[str, Any]) -> str:
    return f"Maestro - {proj.data['slug']} - P{pat['fl_pattern']:02d} {pat['id']}.pyscript"


def export_pianoroll_scripts(proj: Project, pattern_ids: list[str] | None = None,
                             out_dir: Path | None = None) -> dict[str, Any]:
    d = proj.data
    out_dir = out_dir or paths.pianoroll_scripts_dir()
    out_dir.mkdir(parents=True, exist_ok=True)
    ids = pattern_ids or list(d["patterns"])
    written = []
    for pid in ids:
        pat = d["patterns"].get(pid)
        if not pat:
            raise LookupError(f"unknown pattern {pid!r}")
        agent = d["agents"][pat["agent"]]
        notes = ",\n    ".join(
            f"({n['pitch']}, {n['start']!r}, {n['length']!r}, {round(n['velocity'] / 127, 4)!r})"
            for n in pat["notes"])
        text = _SCRIPT.format(
            project=d["name"].replace('"', "'"), pattern_name=pat["name"].replace('"', "'"),
            agent_name=agent["name"].replace('"', "'"), agent_id=agent["id"],
            channel=agent["channel"], fl_pattern=pat["fl_pattern"], length=pat["length_beats"],
            notes=f"[\n    {notes},\n]" if notes else "[]", count=len(pat["notes"]))
        path = out_dir / script_name(proj, pat)
        path.write_text(text, encoding="utf-8")
        written.append({"pattern": pid, "fl_pattern": pat["fl_pattern"], "channel": agent["channel"],
                        "script": path.name})
    return {"folder": str(out_dir), "scripts": written}
